// lib/data/adapters/mock/daily_service_mock.dart
//
// Demo metric snapshots and coach copy, all derived from DemoData.
import '../../demo_data.dart';
import '../../models/vitality_metrics.dart';

class DailyServiceMock {
  const DailyServiceMock();

  static const String _source = 'Fitbit';

  List<MetricSnapshot> snapshots() => [
        _snapshot(
          VitalityMetric.sleep,
          label: 'Sleep',
          shortLabel: 'Sleep',
          unit: 'h',
          value: (d) => d.sleepHours,
          about: 'Total sleep last night. It feeds your sleep score.',
        ),
        _snapshot(
          VitalityMetric.hrv,
          label: 'HRV',
          shortLabel: 'HRV',
          unit: 'ms',
          value: (d) => d.hrvMs,
          about: 'Heart rate variability while you sleep, compared with your own recent average. '
              'It feeds your recovery score.',
        ),
        _snapshot(
          VitalityMetric.restingHr,
          label: 'Resting HR',
          shortLabel: 'RHR',
          unit: 'bpm',
          lowerIsBetter: true,
          value: (d) => d.restingHrBpm,
          about: 'Resting heart rate, compared with your own recent average. It feeds your recovery score.',
        ),
        _snapshot(
          VitalityMetric.steps,
          label: 'Steps (yesterday)',
          shortLabel: 'Steps',
          unit: 'steps',
          completeDaysOnly: true,
          value: (d) => d.steps.toDouble(),
          about: "Yesterday's total. It feeds your activity score, because today isn't finished yet.",
        ),
      ];

  MetricSnapshot _snapshot(
    VitalityMetric metric, {
    required String label,
    required String shortLabel,
    required String unit,
    required double Function(DemoDayMetrics) value,
    required String about,
    bool lowerIsBetter = false,
    bool completeDaysOnly = false,
  }) {
    final skip = completeDaysOnly ? 1 : 0;
    final days = DemoData.metricHistory(30 + skip);
    final history = days.sublist(0, days.length - skip);
    return MetricSnapshot(
      metric: metric,
      label: label,
      shortLabel: shortLabel,
      value: value(history.last),
      unit: unit,
      average30: DemoData.average(value, fromDaysAgo: 30 + skip, toDaysAgo: skip),
      source: _source,
      about: about,
      lowerIsBetter: lowerIsBetter,
      history: history.map((d) => MetricPoint(d.date, value(d))).toList(),
    );
  }

  String get _nextStep => switch (DemoData.largestDriver) {
        'activity' => 'a short walk is a good place to start',
        'sleep' => 'an earlier night is a good place to start',
        _ => 'an easier day is a good place to start',
      };

  /// The coach line on Home. Templated from the sample numbers, not generated by a model.
  String coachInsight() {
    final years = (DemoData.chronoAge - DemoData.vitalityAge).toStringAsFixed(1);
    final hrv = DemoData.today.hrvMs.round();
    final hrvAverage = DemoData.average((d) => d.hrvMs, fromDaysAgo: 30).round();
    final comparison = hrv > hrvAverage ? 'above' : (hrv < hrvAverage ? 'below' : 'level with');
    final driver = VitalityWhy.groupLabel(DemoData.largestDriver);
    return '${DemoData.firstName}, you\'re $years years younger than your actual age. '
        'HRV is $hrv ms, $comparison your 30-day average of $hrvAverage. '
        '$driver is your largest driver today, so $_nextStep.';
  }

  /// The coach panel's opening message.
  String coachSnapshot() {
    final today = DemoData.today;
    return "Today's snapshot:\n"
        '• Vitality Age ${DemoData.vitalityAge.toStringAsFixed(1)}\n'
        '• Sleep ${today.sleepHours.toStringAsFixed(1)} h\n'
        '• HRV ${today.hrvMs.round()} ms\n'
        '• Resting heart rate ${today.restingHrBpm.round()} bpm';
  }

  static const List<String> coachQuestions = [
    'What changed most?',
    'How confident is this?',
    'Give me a plan',
  ];

  /// The metric furthest from its own 30-day average, in percent.
  MetricSnapshot _mostChanged() {
    double gap(MetricSnapshot s) => s.average30 == 0 ? 0 : ((s.value - s.average30) / s.average30).abs();
    return snapshots().reduce((a, b) => gap(b) > gap(a) ? b : a);
  }

  /// Answers to the coach panel's quick replies. Templated, like [coachInsight].
  String coachReply(String question) {
    switch (question) {
      case 'What changed most?':
        final s = _mostChanged();
        final direction = s.value >= s.average30 ? 'above' : 'below';
        return '${s.label}. It\'s at ${s.displayWithUnit}, $direction your 30-day average of '
            '${s.format(s.average30)} ${s.unit}.';
      case 'How confident is this?':
        return 'Confidence is ${DemoData.confidence}%. All four core inputs are present and up to date. '
            'That\'s the most they can add without slow anchors such as VO2max.';
      default:
        final driver = VitalityWhy.groupLabel(DemoData.largestDriver).toLowerCase();
        return 'Your largest driver today is $driver, so $_nextStep. '
            'Tonight: in bed by 10:30 pm to keep your bedtime experiment going.';
    }
  }
}
